with open(os.path.join(OUT, "hockey_calendar.json"), "w", encoding="utf-8") as f:
    json.dump(bydate, f, ensure_ascii=False, indent=2)

all_days = []
for m in range(1, 13):
    for d in range(1, calendar.monthrange(2024, m)[1] + 1):
        all_days.append(f"{m:02d}-{d:02d}")
missing = [d for d in all_days if d not in bydate]
print("Всего событий:", len(E))
print("Покрыто дней:", len(bydate), "из 366")
print("Пустые дни:", len(missing))

RU_MONTHS = ["", "января","февраля","марта","апреля","мая","июня",
             "июля","августа","сентября","октября","ноября","декабря"]
with open(os.path.join(OUT, "gaps_to_fill.txt"), "w", encoding="utf-8") as f:
    f.write("ПУСТЫЕ ДНИ (нужно найти событие). Всего: %d\n\n" % len(missing))
    for d in missing:
        m, day = d.split("-")
        f.write(f"{int(day)} {RU_MONTHS[int(m)]}  ({d})\n")

